BEGIN;
CREATE TYPE "AuditActorKind" AS ENUM ('USER','MEMBER','SYSTEM','INTEGRATION');
CREATE TYPE "AuditSource" AS ENUM ('HTTP','DOMAIN_WORKER','INTERNAL');
CREATE TABLE audit_events (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  workspace_id uuid NOT NULL REFERENCES provider_workspaces(id) ON DELETE RESTRICT ON UPDATE RESTRICT,
  action varchar(120) NOT NULL,
  schema_version integer NOT NULL,
  actor_kind "AuditActorKind" NOT NULL,
  actor_user_id uuid,
  actor_membership_id uuid,
  system_purpose varchar(80),
  resource_type varchar(80) NOT NULL,
  resource_id uuid NOT NULL,
  listing_id uuid,
  resource_revision_before integer,
  resource_revision_after integer,
  revision_kind varchar(80),
  occurred_at timestamptz(3) NOT NULL,
  recorded_at timestamptz(3) NOT NULL DEFAULT clock_timestamp(),
  source "AuditSource" NOT NULL,
  correlation_id uuid NOT NULL,
  causation_id uuid,
  command_id uuid NOT NULL,
  command_scope varchar(120) NOT NULL,
  effect_key varchar(160) NOT NULL,
  source_evidence_type varchar(80),
  source_evidence_id uuid,
  changes jsonb NOT NULL,
  metadata jsonb NOT NULL,
  CONSTRAINT audit_event_action_version CHECK(action='audit.ledger.activated' AND schema_version=1),
  CONSTRAINT audit_event_actor CHECK ((
    (actor_kind='USER' AND actor_user_id IS NOT NULL AND actor_membership_id IS NULL AND system_purpose IS NULL) OR
    (actor_kind='MEMBER' AND actor_user_id IS NOT NULL AND actor_membership_id IS NOT NULL AND system_purpose IS NULL) OR
    (actor_kind='SYSTEM' AND actor_user_id IS NULL AND actor_membership_id IS NULL AND system_purpose='AUDIT_LEDGER_ACTIVATION')) IS TRUE),
  -- Reserved model fields cannot turn the sole foundation action into an
  -- arbitrary entity, resource, integration or business-event insertion path.
  CONSTRAINT audit_event_foundation CHECK (
    resource_type='WORKSPACE' AND resource_id=workspace_id AND source='INTERNAL'
    AND command_scope='audit.ledger.activation' AND effect_key='activation'
    AND listing_id IS NULL AND resource_revision_before IS NULL
    AND resource_revision_after IS NULL AND revision_kind IS NULL
    AND source_evidence_type IS NULL AND source_evidence_id IS NULL),
  CONSTRAINT audit_event_payload CHECK (
    changes='{}'::jsonb AND metadata='{"activationVersion":1}'::jsonb
    AND octet_length(changes::text)+octet_length(metadata::text)<=8192),
  CONSTRAINT audit_event_finite_time CHECK(isfinite(occurred_at) AND isfinite(recorded_at))
);
CREATE UNIQUE INDEX audit_event_command_effect ON audit_events(workspace_id,command_scope,command_id,effect_key);
CREATE UNIQUE INDEX audit_event_source_evidence ON audit_events(workspace_id,source_evidence_type,source_evidence_id,action);
CREATE INDEX audit_event_workspace_page ON audit_events(workspace_id,recorded_at,id);
CREATE INDEX audit_event_resource_page ON audit_events(workspace_id,resource_type,resource_id,recorded_at,id);
CREATE INDEX audit_event_listing_page ON audit_events(workspace_id,listing_id,recorded_at,id);
-- No audit records are generated by this migration. Historical identity UUIDs
-- are validated on insertion, not cascading FKs that rewrite/delete evidence.
COMMIT;
